# Build SlideDock.exe with the C# compiler that ships with Windows (.NET Framework 4.8).
# No Visual Studio or .NET SDK needed.
#   powershell -ExecutionPolicy Bypass -File build.ps1
#   powershell -ExecutionPolicy Bypass -File build.ps1 -Out dist\SlideDock.exe
param(
  [switch]$NoSdk,      # test the fallback that works on any Windows 10/11 PC
  [string]$Out = ''    # output path (default: SlideDock.exe next to this script)
)

$ErrorActionPreference = 'Stop'
$fw   = 'C:\Windows\Microsoft.NET\Framework64\v4.0.30319'
$wpf  = "$fw\WPF"
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
if (-not (Test-Path "$fw\csc.exe")) { throw ".NET Framework 4.8 compiler not found at $fw" }
if ($Out -eq '') { $Out = Join-Path $here 'SlideDock.exe' }
elseif (-not [System.IO.Path]::IsPathRooted($Out)) { $Out = Join-Path $here $Out }
New-Item -ItemType Directory -Force (Split-Path -Parent $Out) | Out-Null

# Version comes from the VERSION file (e.g. 0.1.0). The app compares it with the latest GitHub release.
$version = '0.0.0'
if (Test-Path "$here\VERSION") { $version = (Get-Content "$here\VERSION" -Raw).Trim() }
if ($version -notmatch '^\d+\.\d+\.\d+$') { throw "VERSION must look like 1.2.3 (got '$version')" }
$year = (Get-Date).Year
New-Item -ItemType Directory -Force "$here\obj" | Out-Null
$info = "$here\obj\AssemblyInfo.g.cs"
@"
// generated by build.ps1 from VERSION - do not edit
using System.Reflection;
[assembly: AssemblyTitle("SlideDock")]
[assembly: AssemblyProduct("SlideDock")]
[assembly: AssemblyDescription("A modern dock that replaces the Windows taskbar")]
[assembly: AssemblyCompany("SlideDock")]
[assembly: AssemblyCopyright("Copyright (c) $year Ramadhoni Nasri")]
[assembly: AssemblyVersion("$version.0")]
[assembly: AssemblyFileVersion("$version.0")]
[assembly: AssemblyInformationalVersion("$version")]
"@ | Set-Content -Path $info -Encoding UTF8

$refs = @(
  "$wpf\PresentationFramework.dll", "$wpf\PresentationCore.dll", "$wpf\WindowsBase.dll",
  "$fw\System.Xaml.dll", "$fw\System.Windows.Forms.dll", "$fw\System.Drawing.dll",
  "$fw\System.Core.dll", "$fw\System.Data.dll", "$fw\System.Management.dll", "$fw\System.dll",
  "$fw\System.Runtime.WindowsRuntime.dll", "$fw\System.Runtime.InteropServices.WindowsRuntime.dll", "$fw\System.Runtime.dll", "$fw\System.Web.Extensions.dll", "$fw\System.Security.dll"
)

# Windows Runtime metadata (notifications API): use the Windows SDK if installed,
# otherwise the metadata files every Windows 10/11 already has.
$sdk = Get-ChildItem 'C:\Program Files (x86)\Windows Kits\10\UnionMetadata\*\Windows.winmd' -ErrorAction SilentlyContinue |
       Where-Object { $_.Directory.Name -match '^\d+(\.\d+)+$' } |          # version folders only (skip "Facade")
       Sort-Object { [version]$_.Directory.Name } -Descending | Select-Object -First 1
if ($sdk -and -not $NoSdk) {
  $refs += $sdk.FullName
} else {
  $refs += (Get-ChildItem "$env:windir\System32\WinMetadata\*.winmd").FullName
}

$cscArgs = @($refs | ForEach-Object { "/r:$_" })
if (Test-Path "$here\assets\SlideDock.ico") { $cscArgs += "/win32icon:$here\assets\SlideDock.ico" }
& "$fw\csc.exe" /nologo /codepage:65001 /target:winexe "/win32manifest:$here\app.manifest" /optimize+ "/out:$Out" @cscArgs "$here\SlideDock.cs" $info
if ($LASTEXITCODE -ne 0) { throw "Build failed" }
"Build OK: $Out (v$version)"
